// Builds nn/nn-bot.js: one file you can paste into the Chrome console on
// chrome://dino to watch the trained neural network play.
//
//   node nn/export.js        (run after nn/train.js)

const fs = require('fs');
const path = require('path');

const brain = JSON.parse(fs.readFileSync(path.join(__dirname, 'brain.json'), 'utf8'));
const network = fs.readFileSync(path.join(__dirname, 'network.js'), 'utf8');
const weights = brain.weights.map(w => +w.toFixed(4));

const out = `// Chrome Dino, played by a neural network (trained for ${brain.generation} generations).
// Paste this into the DevTools console on chrome://dino, then press Space.
// Run stopDinoBrain() to turn it off. Generated by nn/export.js; do not edit by hand.

${network}
(() => {
  const WEIGHTS = ${JSON.stringify(weights)};
  let on = true;
  const loop = () => { if (!on) return; DinoNet.step(WEIGHTS); requestAnimationFrame(loop); };
  requestAnimationFrame(loop);
  window.stopDinoBrain = () => { on = false; };
  console.log('Neural network is playing. Press Space to start, stopDinoBrain() to stop.');
})();
`;
fs.writeFileSync(path.join(__dirname, 'nn-bot.js'), out);
console.log(`Wrote nn/nn-bot.js (${weights.length} weights, generation ${brain.generation})`);
